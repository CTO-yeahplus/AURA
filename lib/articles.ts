/** 배포본에서는 발행한 글만, 개발 서버에서는 초안도 보인다. */
export const SHOW_DRAFTS = process.env.NODE_ENV !== "production";

export function visibleArticles(): Article[] {
  return ARTICLES.filter((a) => a.published || SHOW_DRAFTS);
}
export function publishedArticles(): Article[] {
  return ARTICLES.filter((a) => a.published);
}
export function findArticle(slug: string): Article | undefined {
  return visibleArticles().find((a) => a.slug === slug);
}

/** **굵게** · [글자](주소) 표기를 걷어 낸 글자만 — 구조화 데이터 · 설명문에 쓴다. */
export function plain(text: string): string {
  return text.replace(/\*\*([^*]+)\*\*/g, "$1").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
}

/** "2026-11-17" → "2026년 11월" */
export function monthLabel(iso: string): string {
  const [y, m] = iso.split("-");
  return `${y}년 ${Number(m)}월`;
}
