export type ArticleBlock =
  | { t: "h2"; text: string }
  | { t: "p"; text: string }
  | { t: "ul"; items: string[] }
  | { t: "ol"; items: string[] }
  | { t: "table"; head: string[]; rows: string[][] }
  /** 성격 소개 끝의 두 줄 — 잘 맞는 사람 / 알아 둘 점. */
  | { t: "fit"; good: string; note: string };

export type Article = {
  slug: string;
  category: "Fashion" | "Beauty" | "Lifestyle";
  /** 검색 결과 첫 줄 — 겨냥 검색어를 앞쪽에. */
  title: string;
  /** 검색 결과 둘째 줄(meta description). */
  description: string;
  /** 처음 올린 날 · 마지막으로 고친 날(YYYY-MM-DD) — 구조화 데이터와 화면 표기에 쓴다. */
  published_at: string;
  updated_at: string;
  published: boolean;
  /** 글 첫머리에 밝히는 말(누가 썼는지 · 이해관계). */
  disclosure?: string;
  /** 첫 문단 — 질문에 바로 답한다. */
  lead: string;
  blocks: ArticleBlock[];
  faq: { q: string; a: string }[];
  /** 글 끝의 한 문단(앱 · 오늘의 룩으로 잇는 말). */
  outro: string;
};

